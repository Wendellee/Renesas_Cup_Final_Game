const fs = require('fs');
const path = require('path');

const webRoot = path.resolve(__dirname, '..', 'web');
const models = [
  'assets/model/robot-chassis.stl',
  'assets/model/vehicle-boards/ra8p1-baseboard.stl',
  'assets/model/vehicle-boards/motor-driver-board.stl',
  'assets/model/vehicle-boards/sandwich-board-v3.stl',
  'assets/model/vehicle-boards/lcd-v3-1.stl',
  'assets/model/vehicle-boards/ov5640-camera-board.stl',
];

const entries = models.map((modelPath) => {
  const encoded = fs.readFileSync(path.join(webRoot, modelPath)).toString('base64');
  return `  ${JSON.stringify(modelPath)}: ${JSON.stringify(encoded)}`;
});

const output = `/* Generated by report/scripts/build-model-data.js. */\nwindow.__EMBEDDED_STL__ = {\n${entries.join(',\n')}\n};\n`;
fs.writeFileSync(path.join(webRoot, 'assets', 'model', 'model-data.js'), output);
process.stdout.write(`Embedded ${models.length} STL models (${Buffer.byteLength(output)} bytes).\n`);
