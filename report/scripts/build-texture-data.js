const fs = require('fs');
const path = require('path');

const webRoot = path.resolve(__dirname, '..', 'web');
const texturePath = 'assets/model/vehicle-boards/sandwich-board-jlc-top.png';
const encoded = fs.readFileSync(path.join(webRoot, texturePath)).toString('base64');
const output = `/* Generated by report/scripts/build-texture-data.js. */\nwindow.__EMBEDDED_TEXTURE__ = {\n  ${JSON.stringify(texturePath)}: ${JSON.stringify(`data:image/png;base64,${encoded}`)}\n};\n`;

fs.writeFileSync(path.join(webRoot, 'assets', 'model', 'texture-data.js'), output);
process.stdout.write(`Embedded texture (${Buffer.byteLength(output)} bytes).\n`);
